"""Replace the (large) element lists of images_a_c_k.json by small generating sets: the image at each level is  <generators>  (reconstruct with image.generate)."""
import sys, json, random
from image import generate, compose, IDENT
fn = sys.argv[1]; data = json.load(open(fn)); rng = random.Random(7); out = {}
for lvl, elems in data.items():
    q = 2**int(lvl); G = {tuple(e) for e in elems}; gens = []; S = {IDENT}
    while len(S) < len(G):
        g = rng.choice(elems); g = tuple(g)
        if g not in S: gens.append(g); S = generate(gens, q)
    assert S == G; out[lvl] = {"modulus": q, "order_log2": len(G).bit_length() - 1, "generators": gens}
    print("level 2^%s: |I| = 2^%d generated by %d elements" % (lvl, len(G).bit_length() - 1, len(gens)), flush=True)
json.dump(out, open(fn.replace('images_', 'image_generators_'), 'w'), indent=1)
