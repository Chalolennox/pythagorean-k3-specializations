import os
import sys
from collections import Counter

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
B = int(sys.argv[1]) if len(sys.argv) > 1 else 100000
import verify_eligible_triples as v

ok_all = True


def check(name, cond):
    global ok_all
    print(("ok   " if cond else "FAIL ") + name)
    ok_all = ok_all and cond


def cyc(*cycles):
    p = list(range(13))
    for c in cycles:
        for i in range(len(c)):
            p[c[i]] = c[(i + 1) % len(c)]
    return tuple(p[1:])  # image of 1..12


GENS = [
    cyc((1, 8, 5, 3, 11, 9), (2, 12, 10), (4, 7, 6)),
    cyc((1, 11, 10), (2, 12, 9, 4, 7, 5), (3, 8, 6)),
    cyc((8, 11)), cyc((5, 9)), cyc((7, 12)), cyc((2, 4)),
    cyc((1, 9), (2, 10), (3, 5), (4, 6), (7, 12)),
    cyc((1, 3)),
    cyc((1, 6, 3, 10), (2, 9, 4, 5), (7, 12)),
    cyc((6, 10)),
]
PAIRS = [(1, 3), (2, 4), (5, 9), (6, 10), (7, 12), (8, 11)]


def compose(a, b):  # apply a then b (images of points 1..12 stored 0-based)
    return tuple(b[a[i] - 1] for i in range(12))


identity = tuple(range(1, 13))
grp = {identity}
frontier = [identity]
while frontier:
    new = []
    for g in frontier:
        for s in GENS:
            h = compose(g, s)
            if h not in grp:
                grp.add(h)
                new.append(h)
    frontier = new
check("(1) group generated by the 10 archived generators has order %d (attested: 1536)" % len(grp), len(grp) == 1536)
check("(1) transitive on 12 points", len({g[0] for g in grp}) == 12)
check("(1) contains the six single-pair transpositions", all(cyc(pr) in grp for pr in PAIRS))
partner = {}
for a, b in PAIRS:
    partner[a], partner[b] = b, a
check("(3) pairing preserved by every group element", all(partner[g[i - 1]] == g[partner[i] - 1] for g in grp for i in range(1, 13)))
# uniqueness of equivariant fixed-point-free involution: the image of 1 determines the map (transitivity); test all 11 candidates
stab = None
cands = 0
for j in range(2, 13):
    f = {}
    good = True
    for g in grp:
        a, b = g[0], g[j - 1]  # g sends 1->a and j->b, so an equivariant f must send a->b
        if f.setdefault(a, b) != b:
            good = False
            break
    if good and len(f) == 12 and len(set(f.values())) == 12 and all(f[f[i]] == i for i in f) and all(f[i] != i for i in f):
        cands += 1
check("(3) exactly one equivariant fixed-point-free involution (candidates found: %d)" % cands, cands == 1)
# signed permutation character
idx = {}
for k, (a, b) in enumerate(PAIRS):
    idx[a] = (k, 1)
    idx[b] = (k, -1)
hist = Counter()
for g in grp:
    t = 0
    for k, (a, b) in enumerate(PAIRS):
        j, s = idx[g[a - 1]]
        if j == k:
            t += s
    hist[t] += 1
want = {-6: 1, -4: 6, -2: 159, 0: 1204, 2: 159, 4: 6, 6: 1}
check("(1) trace histogram of the signed permutation representation = %s" % dict(sorted(hist.items())), dict(hist) == want)


def cycle_type(g):
    seen, ct = set(), []
    for i in range(1, 13):
        if i in seen:
            continue
        n, j = 0, i
        while j not in seen:
            seen.add(j)
            j = g[j - 1]
            n += 1
        ct.append(n)
    return tuple(sorted(ct))


gt = Counter(cycle_type(g) for g in grp)

# (2) factorization patterns of R mod p
R = {12: 1, 10: -66, 8: -29922, 6: 73214, 4: -62559, 2: 22032, 0: -3456}
Rc = [R.get(i, 0) for i in range(13)]


def pattern(p):
    f = v.pnorm([c % p for c in Rc])
    d = v.pnorm([(i * f[i]) % p for i in range(1, len(f))])
    if not d or len(v.pgcd(f, d, p)) > 1:
        return None
    degs, g, cur = [], f[:], [0, 1]
    for k in range(1, 7):
        if len(g) <= 1:
            break
        cur = v.ppowx_shift(cur, p, g, p)
        dd = cur + [0] * (2 - len(cur))
        dd = dd[:]
        dd[1] = (dd[1] - 1) % p
        dd = v.pnorm(dd)
        G = g[:] if not dd else v.pgcd(g, dd, p)
        if len(G) > 1:
            degs += [k] * ((len(G) - 1) // k)
            q = [0] * (len(g) - len(G) + 1)
            r = g[:]
            ig = pow(G[-1], -1, p)
            for i in range(len(q) - 1, -1, -1):
                c = r[i + len(G) - 1] * ig % p
                q[i] = c
                for j in range(len(G)):
                    r[i + j] = (r[i + j] - c * G[j]) % p
            g = v.pnorm(q)
            cur = v.pmod(cur, g, p) if len(g) > 1 else cur
    if len(g) > 1:
        degs += [len(g) - 1]
    return tuple(sorted(degs))


obs = Counter()
n = 0
for p in v.primes_upto(B):
    if p < 5 or p == 23:
        continue
    pt = pattern(p)
    if pt is None:
        continue
    obs[pt] += 1
    n += 1
chi2, dof = 0.0, 0
for ct, c in gt.items():
    e = n * c / 1536
    chi2 += (obs[ct] - e) ** 2 / e
    dof += 1
extra = sum(c for ct, c in obs.items() if ct not in gt)
print("(2) %d primes; %d cycle types in the group; factorization patterns of R mod p not occurring in the group: %d" % (n, len(gt), extra))
for ct in sorted(gt, key=lambda c: -gt[c])[:8]:
    print("      %-24s group %.4f   observed %.4f" % (ct, gt[ct] / 1536, obs[ct] / n))
check("(2) chi-square %.1f on %d cell(s) (rule of thumb: below %d) and no pattern outside the group" % (chi2, dof - 1, 2 * dof), extra == 0 and chi2 < 2 * dof)
sys.exit(0 if ok_all else 1)
