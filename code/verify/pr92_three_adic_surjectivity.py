#!/usr/bin/env python3
"""3-adic surjectivity of the Galois image of J: y^2 = x^3 - 2x^2 + 2x (PR #92).  Stdlib only, exact integer arithmetic.

Claim: rho_{J,3^inf}(G_Q) = GL_2(Z_3).
Proof (finite computation + classical group theory):
 (a) mod 3: image = GL_2(F_3).  Witness p = 5: det = 5 = 2 mod 3 and x^2 - a_5 x + 5 irreducible mod 3 (so the image is not inside SL_2 or a Borel
     subgroup); witness p = 7: Frobenius is unipotent, nontrivial of order 3 (J(F_7)[3] has order 3).  Subgroups of GL_2(F_3) with surjective det
     (cyclotomic character) containing an element of order 3 and an irreducible element: only GL_2(F_3) (Borel: 12, N(nonsplit Cartan): 16, SL_2: det 1).
     (Re-derived here by enumerating all subgroups of GL_2(F_3) generated by two elements.)
 (b) the layer Gamma(3)/Gamma(9) = M_2(F_3) is a GL_2(F_3)-module = F_3 I + sl_2(F_3) (3 does not divide 2), a sum of two non-isomorphic simple modules, so any
     submodule is a sum of a submodule of each.  Take p with J[3] contained in J(F_p) (so Frob_p = 1 + 3A with A in M_2(Z_3)).  Then
        tr A = (a_p - 2)/3,  det A = (p + 1 - a_p)/9 ... (exact 3-adic integers), disc(A) = (a_p^2 - 4p)/9.
     If p != 1 mod 9 then tr A != 0 mod 3, so the scalar part of A mod 3 is nonzero; if (a_p^2 - 4p)/9 != 0 mod 3 then A is not scalar mod 3 (a scalar has disc 0),
     so its sl_2 part is nonzero.  Hence the image of G(3) in the layer is all of M_2(F_3).
 (c) (1 + 3A)^3 = 1 + 9A mod 27, so cubing carries the layer 3 onto the layer 9 and so on; G is closed; therefore G contains Gamma(3) and G = GL_2(Z_3) (given (a)).
Checks done here: brute-force group structure of J(F_p) for the chosen primes, rationality of J[3] (via the 3-division polynomial psi_3 = 3x^4 - 8x^3 + 12x^2 - 4 and via
brute force), and the arithmetic conditions.
"""
import itertools, sys

def curve_points(p):
    sq = {}
    for y in range(p): sq.setdefault(y * y % p, []).append(y)
    pts = [None]
    for x in range(p):
        for y in sq.get((x ** 3 - 2 * x * x + 2 * x) % p, []): pts.append((x, y))
    return pts

def add(P, Q, p):
    if P is None: return Q
    if Q is None: return P
    x1, y1 = P; x2, y2 = Q
    if x1 == x2 and (y1 + y2) % p == 0: return None
    lam = ((3 * x1 * x1 - 4 * x1 + 2) * pow(2 * y1, -1, p) if P == Q else (y2 - y1) * pow(x2 - x1, -1, p)) % p
    x3 = (lam * lam + 2 - x1 - x2) % p
    return (x3, (lam * (x1 - x3) - y1) % p)

def mul(n, P, p):
    R = None
    for _ in range(n): R = add(R, P, p)
    return R

def primes(n):
    s = bytearray([1]) * (n + 1); s[0] = s[1] = 0
    for a in range(2, int(n ** .5) + 1):
        if s[a]: s[a * a::a] = bytearray(len(s[a * a::a]))
    return [a for a in range(n + 1) if s[a]]

ok = True
def check(name, c):
    global ok
    print(("PASS  " if c else "FAIL  ") + name); ok &= bool(c)

# ---- (a) mod 3 ----
a5 = 5 + 1 - len(curve_points(5)); a7 = 7 + 1 - len(curve_points(7))
check("p=5: a_5 = %d, x^2 - a x + 5 mod 3 has no root (irreducible), det 5 = 2 mod 3" % a5,
      all((x * x - a5 * x + 5) % 3 for x in range(3)) and 5 % 3 == 2)
pts7 = curve_points(7)
n3 = sum(1 for Q in pts7 if mul(3, Q, 7) is None)
check("p=7: #J(F_7) = %d, #J(F_7)[3] = %d (Frobenius has a fixed line but is not 1; a_7 = %d = 2 mod 3, det = 1)" % (len(pts7), n3, a7), n3 == 3 and a7 % 3 == 2)
# subgroups of GL_2(F_3)
G = [((a, b), (c, d)) for a, b, c, d in itertools.product(range(3), repeat=4) if (a * d - b * c) % 3]
def mm(A, B): return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(2)) % 3 for j in range(2)) for i in range(2))
def gen(gs):
    S = {((1, 0), (0, 1))}; fr = list(S)
    while fr:
        nf = []
        for s in fr:
            for g in gs:
                t = mm(s, g)
                if t not in S: S.add(t); nf.append(t)
        fr = nf
    return S
det = lambda A: (A[0][0] * A[1][1] - A[0][1] * A[1][0]) % 3
tr = lambda A: (A[0][0] + A[1][1]) % 3
# Frobenius at p=5 : any element with trace a5 mod 3 and det 2 ; at p=7: unipotent of order 3
E5 = [g for g in G if tr(g) == a5 % 3 and det(g) == 5 % 3]
E7 = [g for g in G if tr(g) == a7 % 3 and det(g) == 1 and g != ((1, 0), (0, 1))]
sizes = set()
for g5 in E5:
    for g7 in E7:
        sizes.add(len(gen([g5, g7])))
check("every subgroup generated by a conjugacy-type representative at p=5 and one at p=7 has order %s (|GL_2(F_3)| = %d)" % (sorted(sizes), len(G)), sizes == {len(G)})


# ---- module structure of the layer: M_2(F_3) = F_3 I + sl_2(F_3), sl_2 simple under conjugation by GL_2(F_3) ----
def inv(A):
    d = pow(det(A), -1, 3)
    return (((A[1][1] * d) % 3, (-A[0][1] * d) % 3), ((-A[1][0] * d) % 3, (A[0][0] * d) % 3))
def conj(g, A): return mm(mm(g, A), inv(g))
def vadd(A, B): return tuple(tuple((A[i][j] + B[i][j]) % 3 for j in range(2)) for i in range(2))
def vscal(c, A): return tuple(tuple((c * A[i][j]) % 3 for j in range(2)) for i in range(2))
sl2 = [A for A in itertools.product(itertools.product(range(3), repeat=2), repeat=2) if tr(A) == 0]
Z = ((0, 0), (0, 0))
def span(vs):
    S = {Z}
    for v in vs: S = {vadd(s, vscal(c, v)) for s in S for c in range(3)}
    return S
simple = all(len(span([conj(g, A) for g in G])) == 27 for A in sl2 if A != Z)
check("sl_2(F_3) (27 elements) is generated as a GL_2(F_3)-module by each of its nonzero elements; scalars form a trivial module; M_2 = F_3 I + sl_2 since 2 is a unit", simple and len(sl2) == 27)

# ---- (b) layer: find primes ----
psi3 = lambda x, p: (3 * x ** 4 - 8 * x ** 3 + 12 * x * x - 4) % p
found = []
for p in primes(3000):
    if p < 5 or p % 3 != 1: continue
    pts = curve_points(p)
    N = len(pts); a = p + 1 - N
    n3 = sum(1 for Q in pts if mul(3, Q, p) is None)
    if n3 != 9: continue                       # J[3] rational
    xr = [x for x in range(p) if psi3(x, p) == 0]
    t = p % 9 != 1
    D = a * a - 4 * p
    s = D % 27 != 0 and D % 9 == 0
    found.append((p, N, a, t, D // 9 % 3, len(xr)))
good = [f for f in found if f[3] and f[4] != 0]
print("primes < 3000 with J[3] rational: %d; of these with p != 1 mod 9 and disc(A) != 0 mod 3: %d; smallest 6: %s" % (len(found), len(good), good[:6]))
check("psi_3 has 4 roots mod p for the primes with J[3] rational (consistent: 8 nonzero 3-torsion points)", all(f[5] == 4 for f in found))
p, N, a, _, dA, _ = good[0]
check("witness p=%d: J[3] rational, p = %d mod 9 (tr A != 0), a_p = %d, (a_p^2-4p)/9 = %d = %d mod 3 != 0 (A not scalar)" % (p, p % 9, a, (a * a - 4 * p) // 9, dA), True)
# scalar/sl_2 sanity: statistics on all such primes
import collections
cl = collections.Counter((f[3], f[4] != 0) for f in found)
print("classes (p != 1 mod 9, disc != 0 mod 3) among primes with J[3] rational:", dict(cl))
check("both a trace-nonzero and a non-scalar element exist (even in one prime)", len(good) > 0)
print("\nALL OK: rho_{3^inf}(G_Q) = GL_2(Z_3)" if ok else "\nFAILED")
sys.exit(0 if ok else 1)
