def leg(a, p):
    return pow(a % p, (p - 1) // 2, p)


def sieve(n):
    s = bytearray([1]) * (n + 1)
    s[0:2] = b"\x00\x00"
    for i in range(2, math.isqrt(n) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(range(i * i, n + 1, i)))
    return s


def order(p, pt, add, neg, mul):
    L = math.isqrt(4 * p) + 6
    cur = pt
    for n in range(1, L + 1):
        if cur is None:
            return n
        cur = add(cur, pt)
    return sm.order_bsgs(p, pt, add, neg, mul)


def group_order(p, rts, rng):
    add, neg, mul = sm.group(p)
    pts = [(1, 1)]
    for x in rts:
        y = v.sqrt_mod(v.Yc(x), p)
        if y:
            pts.append((x, y))
    e = 1
    for pt in pts[:5]:
        e = e * order(p, pt, add, neg, mul) // math.gcd(e, order(p, pt, add, neg, mul))
    lo, hi = p + 1 - math.isqrt(4 * p) - 2, p + 1 + math.isqrt(4 * p) + 2
    for _ in range(12):
        cands = [m for m in range((lo + e - 1) // e * e, hi + 1, e)]
        if len(cands) == 1:
            return cands[0], e
        while True:
            x = rng.randrange(p)
            Y = v.Yc(x) % p
            if Y and leg(Y, p) == 1:
                break
        pt = (x, v.sqrt_mod(Y, p))
        o = order(p, pt, add, neg, mul)
        e = e * o // math.gcd(e, o)
    return None, e


def two_exponent(p, N, nu, rng, tries=30):
    """v2 of the exponent of J(F_p), from RANDOM points only (the special points P, U_j may lie in 2 J(F_p) and would hide the exponent): the maximum of v2(order) over random points; a random point
    attains the maximum with probability >= 1/2, so 30 points fail with probability <= 2^-30."""
    add, neg, mul = sm.group(p)
    m = N >> nu
    best = 0
    for _ in range(tries):
        while True:
            x = rng.randrange(p)
            Y = v.Yc(x) % p
            if Y and leg(Y, p) == 1:
                break
        R = mul(m, (x, v.sqrt_mod(Y, p)))
        k = 0
        while R is not None:
            R = add(R, R)
            k += 1
        best = max(best, k)
    return best


def v2(n):
    k = 0
    while n % 2 == 0:
        n //= 2
        k += 1
    return k


def chi2(table):
    rows = [r for r in table if sum(r)]
    cols = [j for j in range(len(table[0])) if sum(r[j] for r in rows)]
    n = sum(sum(r) for r in rows)
    if len(rows) < 2 or len(cols) < 2:
        return 0.0, 0
    rs = [sum(r) for r in rows]
    cs = [sum(r[j] for r in rows) for j in cols]
    x = 0.0
    for i, r in enumerate(rows):
        for jj, j in enumerate(cols):
            e = rs[i] * cs[jj] / n
            x += (r[j] - e) ** 2 / e
    return x, (len(rows) - 1) * (len(cols) - 1)


